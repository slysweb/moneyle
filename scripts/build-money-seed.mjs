function sqlStr(s) {
  return `'${String(s).replaceAll("'", "''")}'`;
}

const currencies = CATALOG;
const lines = [
  "-- Currencies, denominations, and daily puzzle table.",
  "-- Regenerated by: node scripts/build-money-seed.mjs",
  "-- Safe to re-run: does not touch More/Less categories/items.",
  "",
  "-- Recreate daily_puzzles so the game CHECK includes connections.",
  "-- Existing rows are copied first; Guessr/Moneyle/Connections caches are then",
  "-- dropped because they bake in denomination image URLs.",
  "CREATE TABLE IF NOT EXISTS daily_puzzles (",
  "  id          INTEGER PRIMARY KEY AUTOINCREMENT,",
  "  game        TEXT NOT NULL,",
  "  puzzle_date TEXT NOT NULL,",
  "  payload     TEXT NOT NULL,",
  "  created_at  TEXT NOT NULL DEFAULT (datetime('now')),",
  "  UNIQUE (game, puzzle_date)",
  ");",
  "DROP TABLE IF EXISTS daily_puzzles_new;",
  "CREATE TABLE daily_puzzles_new (",
  "  id          INTEGER PRIMARY KEY AUTOINCREMENT,",
  "  game        TEXT NOT NULL CHECK (game IN ('moreless', 'guessr', 'banknotele', 'connections')),",
  "  puzzle_date TEXT NOT NULL,",
  "  payload     TEXT NOT NULL,",
  "  created_at  TEXT NOT NULL DEFAULT (datetime('now')),",
  "  UNIQUE (game, puzzle_date)",
  ");",
  "INSERT INTO daily_puzzles_new (id, game, puzzle_date, payload, created_at)",
  "  SELECT id,",
  "         CASE WHEN game = 'moneyle' THEN 'banknotele' ELSE game END,",
  "         puzzle_date, payload, created_at",
  "  FROM daily_puzzles;",
  "DROP TABLE daily_puzzles;",
  "ALTER TABLE daily_puzzles_new RENAME TO daily_puzzles;",
  "",
  "DELETE FROM daily_puzzles WHERE game IN ('guessr', 'banknotele', 'connections');",
  "",
  "DROP TABLE IF EXISTS denominations;",
  "DROP TABLE IF EXISTS currencies;",
  "",
  "CREATE TABLE currencies (",
  "  id           INTEGER PRIMARY KEY AUTOINCREMENT,",
  "  slug         TEXT NOT NULL UNIQUE,",
  "  name         TEXT NOT NULL,",
  "  code         TEXT NOT NULL,",
  "  symbol       TEXT NOT NULL,",
  "  minor_digits INTEGER NOT NULL DEFAULT 2,",
  "  country      TEXT,",
  "  is_active    INTEGER NOT NULL DEFAULT 1,",
  "  sort_order   INTEGER NOT NULL DEFAULT 0,",
  "  created_at   TEXT NOT NULL DEFAULT (datetime('now'))",
  ");",
  "",
  "CREATE TABLE denominations (",
  "  id           INTEGER PRIMARY KEY AUTOINCREMENT,",
  "  currency_id  INTEGER NOT NULL REFERENCES currencies(id) ON DELETE CASCADE,",
  "  slug         TEXT NOT NULL,",
  "  kind         TEXT NOT NULL CHECK (kind IN ('bill', 'coin')),",
  "  name         TEXT NOT NULL,",
  "  value_cents  INTEGER NOT NULL,",
  "  image_url    TEXT NOT NULL,",
  "  sort_order   INTEGER NOT NULL DEFAULT 0,",
  "  is_active    INTEGER NOT NULL DEFAULT 1,",
  "  UNIQUE (currency_id, slug)",
  ");",
  "",
  "CREATE INDEX idx_denoms_currency_active",
  "  ON denominations (currency_id, is_active, sort_order);",
  "",
];

currencies.forEach((c, i) => {
  lines.push(
    `INSERT INTO currencies (slug, name, code, symbol, minor_digits, country, is_active, sort_order)`,
    `VALUES (${sqlStr(c.slug)}, ${sqlStr(c.name)}, ${sqlStr(c.code)}, ${sqlStr(c.symbol)}, ${c.minorDigits}, ${sqlStr(c.country)}, 1, ${i + 1});`,
    ""
  );
  c.denoms.forEach((d, di) => {
    const url = `/money/${c.slug}/${d.file}`;
    lines.push(
      `INSERT INTO denominations (currency_id, slug, kind, name, value_cents, image_url, sort_order)`,
      `SELECT id, ${sqlStr(d.slug)}, ${sqlStr(d.kind)}, ${sqlStr(d.name)}, ${d.valueMinor}, ${sqlStr(url)}, ${di + 1} FROM currencies WHERE slug = ${sqlStr(c.slug)};`
    );
  });
  lines.push("");
});

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "db", "money.sql");
writeFileSync(out, lines.join("\n") + "\n", "utf8");
console.log(`Wrote ${out} (${currencies.length} currencies)`);
