// Builds db/seed.sql from the processed data files in data/.
// Run the data:* scripts first for each dataset you want refreshed.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { sqlString } from "./lib.mjs";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dataDir = path.join(root, "data");
const outPath = path.join(root, "db", "seed.sql");

function load(name) {
  return JSON.parse(fs.readFileSync(path.join(dataDir, name), "utf8"));
}

const billionaires = load("forbes-top100.json");
const gdp = load("gdp.json");
const athletes = load("athletes-top100.json");
const movies = load("box-office-top100.json");
const companies = load("market-cap-top100.json");

const categories = [
  {
    slug: "billionaires",
    title: "Forbes Billionaires",
    metric_label: "net worth",
    description: "Who is worth more? The world's 100 richest people.",
    icon: "crown",
    source_name: "Forbes Real-Time Billionaires",
    source_url: "https://www.forbes.com/real-time-billionaires/",
    is_active: 1,
    sort_order: 1,
  },
  {
    slug: "country-gdp",
    title: "Country GDP",
    metric_label: "GDP",
    description: "Which economy is bigger? The world's 100 largest economies.",
    icon: "globe",
    source_name: "World Bank",
    source_url: "https://data.worldbank.org/indicator/NY.GDP.MKTP.CD",
    is_active: 1,
    sort_order: 2,
  },
  {
    slug: "player-salaries",
    title: "Player Salaries",
    metric_label: "annual salary",
    description: "Which athlete earns more per year? Soccer, NBA and NFL stars.",
    icon: "trophy",
    source_name: "Forbes / Spotrac / Capology",
    source_url: "https://www.forbes.com/lists/athletes/",
    is_active: 1,
    sort_order: 3,
  },
  {
    slug: "currency-rates",
    title: "Currency Rates",
    metric_label: "value in USD",
    description: "Which currency is worth more against the dollar?",
    icon: "exchange",
    source_name: null,
    source_url: null,
    is_active: 0,
    sort_order: 4,
  },
  {
    slug: "box-office",
    title: "Movie Box Office",
    metric_label: "worldwide gross",
    description: "Which movie made more money at the box office?",
    icon: "film",
    source_name: "Box Office Mojo",
    source_url: "https://www.boxofficemojo.com/chart/ww_top_lifetime_gross/?area=XWW",
    is_active: 1,
    sort_order: 5,
  },
  {
    slug: "market-cap",
    title: "Company Market Cap",
    metric_label: "market cap",
    description: "Which company is worth more on the stock market?",
    icon: "building",
    source_name: "CompaniesMarketCap",
    source_url: "https://companiesmarketcap.com/",
    is_active: 1,
    sort_order: 6,
  },
];

const lines = [
  "-- Generated by scripts/build-seed.mjs — do not edit by hand.",
  `-- Generated at ${new Date().toISOString()}`,
  "",
  "DELETE FROM items;",
  "DELETE FROM categories;",
  "DELETE FROM sqlite_sequence WHERE name IN ('items','categories');",
  "DELETE FROM daily_puzzles WHERE game = 'moreless';",
  "",
];

for (const c of categories) {
  lines.push(
    "INSERT INTO categories (slug, title, metric_label, description, icon, unit_prefix, unit_suffix, source_name, source_url, is_active, sort_order) VALUES (" +
      [
        sqlString(c.slug),
        sqlString(c.title),
        sqlString(c.metric_label),
        sqlString(c.description),
        sqlString(c.icon),
        sqlString("$"),
        sqlString(""),
        sqlString(c.source_name),
        sqlString(c.source_url),
        c.is_active,
        c.sort_order,
      ].join(", ") +
      ");"
  );
}
lines.push("");

function itemInsert(categorySlug, item) {
  return (
    "INSERT INTO items (category_id, name, subtitle, value, display_value, image_url, meta) " +
    `SELECT id, ${sqlString(item.name)}, ${sqlString(item.subtitle)}, ${item.value}, ` +
    `${sqlString(item.displayValue)}, ${sqlString(item.imageUrl)}, ${sqlString(
      JSON.stringify(item.meta)
    )} FROM categories WHERE slug = ${sqlString(categorySlug)};`
  );
}

lines.push("-- Forbes top 100 billionaires");
for (const b of billionaires) {
  lines.push(
    itemInsert("billionaires", {
      name: b.name,
      subtitle: b.source,
      value: b.netWorthUsd,
      displayValue: b.displayValue,
      imageUrl: b.imageUrl,
      meta: { rank: b.rank, country: b.country },
    })
  );
}
lines.push("");

lines.push("-- Top 100 economies by GDP");
for (const g of gdp) {
  lines.push(
    itemInsert("country-gdp", {
      name: g.name,
      subtitle: g.region,
      value: g.gdpUsd,
      displayValue: g.displayValue,
      imageUrl: g.flagUrl,
      meta: { iso2: g.iso2, iso3: g.iso3, year: g.year },
    })
  );
}
lines.push("");

lines.push("-- Top athlete annual salaries (soccer / NBA / NFL)");
for (const a of athletes) {
  lines.push(
    itemInsert("player-salaries", {
      name: a.name,
      subtitle: `${a.sport} · ${a.team}`,
      value: a.salaryUsd,
      displayValue: a.displayValue,
      imageUrl: a.imageUrl,
      meta: { rank: a.rank, sport: a.sport, team: a.team },
    })
  );
}
lines.push("");

lines.push("-- All-time worldwide box office top 100");
for (const m of movies) {
  lines.push(
    itemInsert("box-office", {
      name: m.name,
      subtitle: String(m.year),
      value: m.worldwideGrossUsd,
      displayValue: m.displayValue,
      imageUrl: m.imageUrl,
      meta: { rank: m.rank, year: m.year, imdbId: m.imdbId },
    })
  );
}
lines.push("");

lines.push("-- Largest companies by market capitalization");
for (const c of companies) {
  lines.push(
    itemInsert("market-cap", {
      name: c.name,
      subtitle: c.ticker,
      value: c.marketCapUsd,
      displayValue: c.displayValue,
      imageUrl: c.imageUrl,
      meta: { rank: c.rank, ticker: c.ticker },
    })
  );
}
lines.push("");

fs.writeFileSync(outPath, lines.join("\n"));
const total =
  billionaires.length +
  gdp.length +
  athletes.length +
  movies.length +
  companies.length;
console.log(
  `Wrote ${outPath}: ${categories.length} categories, ${total} items`
);
